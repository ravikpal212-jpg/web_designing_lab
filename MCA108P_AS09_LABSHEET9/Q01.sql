CREATE DATABASE IF NOT EXISTS webapp_db;
USE webapp_db;
CREATE TABLE users(id INT AUTO_INCREMENT PRIMARY KEY,name VARCHAR(80) NOT NULL,email VARCHAR(120) UNIQUE NOT NULL,password VARCHAR(255) NOT NULL);
CREATE TABLE products(id INT AUTO_INCREMENT PRIMARY KEY,name VARCHAR(100) NOT NULL,category VARCHAR(60),price DECIMAL(10,2) NOT NULL);
CREATE TABLE orders(id INT AUTO_INCREMENT PRIMARY KEY,user_id INT NOT NULL,product_id INT NOT NULL,qty INT NOT NULL,FOREIGN KEY(user_id) REFERENCES users(id),FOREIGN KEY(product_id) REFERENCES products(id));
